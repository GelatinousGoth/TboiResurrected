function mod:GetCostumePrefix(p)
  local prefix = false
  local characterBased = mod.Characters[p:GetPlayerType()]
  if characterBased then
    prefix = characterBased
  else
    if p:HasCollectible(CollectibleType.COLLECTIBLE_STIGMATA) then
      prefix = "costumes_tears_redb"
    end
    if p:HasCollectible(CollectibleType.COLLECTIBLE_POP) or p:HasCollectible(CollectibleType.COLLECTIBLE_HAEMOLACRIA) then
      prefix = "costumes_tears_red"
    end
  end
  
  if prefix then
    return "gfx/characters/" .. prefix .. "/"
  else
    return false
  end
end


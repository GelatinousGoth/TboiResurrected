function mod:ReplaceItemCostume(p, id, isNull)
  local prefix = mod:GetCostumePrefix(p)
  local costumeData = mod.ItemCostumes[id]
  local config = itemConfig:GetCollectible(id)
  
  if isNull then
    costumeData = mod.NullCostumes[id]
    config = itemConfig:GetNullItem(id)
  end
  
  local path = prefix .. costumeData.pngPath
  if costumeData.hasSkinAlt then
    if costumeData.isBody then
      path = path .. mod.SkinColorToPostfix[p:GetBodyColor()]
    else
      path = path .. mod.SkinColorToPostfix[p:GetHeadColor()]
    end
  end
  path = path .. ".png"
  p:ReplaceCostumeSprite(config, path, 0)
  
  if costumeData.extraCostume then
    local extraCostume = Isaac.GetCostumeIdByPath("gfx/characters/bugfix/" .. costumeData.extraCostume.anm2Path .. ".anm2")
    p:AddNullCostume(extraCostume)
    local extraPath = prefix .. costumeData.extraCostume.pngPath
    if costumeData.extraCostume.hasSkinAlt then
      extraPath = extraPath .. mod.SkinColorToPostfix[p:GetBodyColor()]
    end
    extraPath = extraPath .. ".png"
    p:ReplaceCostumeSprite(itemConfig:GetNullItem(extraCostume), extraPath, 0)
    
    local d = p:GetData()
    if not d.ConsistentTearsExtra then d.ConsistentTearsExtra = {} end
    table.insert(d.ConsistentTearsExtra, id)
  end
end

function mod:UpdateCostumes(p)
  for key, costume in pairs(mod.ItemCostumes) do
    if p:HasCollectible(key, true) then
      mod:ReplaceItemCostume(p, key)
    end
  end

  local extraCostumes = p:GetData().ConsistentTearsExtra or {}
  for key = #extraCostumes, 1, -1 do
    if not p:HasCollectible(extraCostumes[key], true) then
      local costume = mod.ItemCostumes[extraCostumes[key]].extraCostume
      p:TryRemoveNullCostume("bugfix" .. costume.anm2Path .. ".anm2")
      table.remove(p:GetData().ConsistentTearsExtra, key)
    end
  end
end

mod:AddCallback(ModCallbacks.MC_POST_PEFFECT_UPDATE, function(_, p)
  local collectibleCount = p:GetCollectibleCount()
  local oldCount = p:GetData().ConsistentTearsCollectibleCount or 0
  if collectibleCount ~= oldCount then
    local prefix = mod:GetCostumePrefix(p)
    if prefix then
      mod:UpdateCostumes(p)
    end
    p:GetData().ConsistentTearsCollectibleCount = collectibleCount
  end
end)

mod:AddCallback(ModCallbacks.MC_POST_NEW_ROOM, function(_)
  local players = mod.GetPlayers()
  for _, p in pairs(players) do
    local prefix = mod:GetCostumePrefix(p)
    if prefix then
      mod:UpdateCostumes(p)
    end
  end
end)

mod:AddCallback(ModCallbacks.MC_USE_ITEM, function(_, item, rng, p)
  local prefix = mod:GetCostumePrefix(p)
  if prefix then
    if mod.ItemCostumes[item] then mod:ScheduleForUpdate(function() mod:ReplaceItemCostume(p, item) end) end
    if item == CollectibleType.COLLECTIBLE_CLICKER then
      mod:UpdateCostumes(p)
    end
  end
end)

